export function localEpilogue(game) {
  const fooled = game.chat.filter((m) => m.fake && !m.flagResult).length;
  const caught = game.chat.filter((m) => m.fake && m.flagResult === 'echo').length;
  const parts = [];
  if (fooled > 0) parts.push(`سجل الأرشيف: الصدى تكلّم بصوتيكما ${fooled} ${fooled === 1 ? 'مرة' : 'مرات'} دون أن تكشفاه. في مكان ما، ما زال يتدرّب.`);
  else if (caught > 0) parts.push('سجل الأرشيف: كشفتما كل محاولات الصدى لانتحال صوتيكما. نادرًا ما يحدث ذلك.');
  const found = Object.values(game.fragments).filter(Boolean).length;
  if (found === 3) parts.push('جمعتما أوراق سلمى كاملة. القصة الآن في عهدتكما.');
  else if (found === 0) parts.push('لم تقرآ شيئًا من أوراق سلمى. ربما في المرة القادمة تعرفان من كانت.');
  return parts.join(' ');
}

